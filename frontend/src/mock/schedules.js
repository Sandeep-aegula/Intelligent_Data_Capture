// Flat list of schedule activities for table views
export const getMockScheduleActivities = (projectId) => {
  const activities = [];
  const flatten = (node, path = []) => {
    const currentPath = [...path, node.name];
    activities.push({
      ...node,
      hierarchyPath: currentPath.join(' → '),
      children: undefined,
    });
    if (node.children) {
      node.children.forEach((child) => flatten(child, currentPath));
    }
  };

  const hierarchy = mockScheduleHierarchy[projectId];
  if (hierarchy) {
    flatten(hierarchy);
  }
  return activities;
};
